// Generates src/icons.ts (inline SVG paths) from the simple-icons package.
// Run once: node scripts/gen-icons.mjs   (simple-icons is a devDependency, not shipped)
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

// Same marks as the Figma design's skills row, in the same order. [slug, label, colour override]
const list = [
  ["figma", "Figma"], ["androidstudio", "Android Studio"], ["kotlin", "Kotlin"], ["flutter", "Flutter", "54C5F8"],
  ["dart", "Dart"], ["javascript", "JavaScript"], ["css", "CSS"],
  ["r", "R"], ["git", "Git"], ["meta", "Meta"], ["render", "Render", "FFFFFF"], ["html5", "HTML5"], ["mongodb", "MongoDB"],
];
const out = list.map(([slug, label, hex]) => {
  const i = si["si" + slug[0].toUpperCase() + slug.slice(1)];
  if (!i) throw new Error("missing " + slug);
  return { label, path: i.path, color: "#" + (hex ?? i.hex) };
});
writeFileSync(
  new URL("../src/icons.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs from simple-icons (CC0). Do not edit by hand.\nexport const skillIcons = ${JSON.stringify(out, null, 2)} as const;\n`
);
console.log("wrote", out.length, "icons");
